"""Validation state: what each claim's assertions said when the drift run last ran them.

docs/design.md: Validation state and freshness. `validation.json` is generated by the drift
run (`tests/test_drift.py`) and shipped in each release.
"""

from __future__ import annotations

import hashlib
import json
import logging
from datetime import date  # noqa: TC003 (pydantic resolves field types at runtime)
from functools import cache
from typing import TYPE_CHECKING

from pydantic import Field

from opendata_atlas.portals.checkers import Outcome  # noqa: TC001 (pydantic field type)
from opendata_atlas.portals.model import SoqlProbe, _Strict
from opendata_atlas.portals.packfile import PORTALS_DIR, PackError, validate_file

if TYPE_CHECKING:
    from collections.abc import Mapping
    from pathlib import Path

    from opendata_atlas.portals.model import Claim

VALIDATION_PATH = PORTALS_DIR / "validation.json"

log = logging.getLogger(__name__)


class ClaimCheck(_Strict):
    checked_at: date
    outcome: Outcome
    #: The outcome of the run before `checked_at`; None for a claim's first run.
    previous_outcome: Outcome | None = None
    #: `assertion_digest` of the claim as checked; the gate fails an entry whose digest no
    #: longer matches the pack. None only in files written before it was recorded.
    assertion_digest: str | None = None


class ValidationFile(_Strict):
    #: Canonical portal id, then claim id.
    portals: dict[str, dict[str, ClaimCheck]] = Field(default_factory=dict)


#: Read by `load_validation()` in place of `VALIDATION_PATH`; set only by `set_override`.
_override: Path | None = None


def load_validation(path: Path | None = None) -> ValidationFile:
    """Read a validation file; a missing one is empty. Only the default path is cached.

    With no `path`, the default is `VALIDATION_PATH`, or the path given to `set_override`. A
    missing `VALIDATION_PATH` is logged as a warning: the release ships it, and without it no
    claim can go stale.
    """
    return _default() if path is None else _read(path)


def set_override(path: Path | None) -> None:
    """Make `load_validation()` read `path` instead of `VALIDATION_PATH`; None restores it.

    For the eval capture server (`scripts/capture_server.py --validation`) and tests only: the
    product has no configuration for the validation path. Clears the cached default, so call it
    before any portal context is loaded.
    """
    global _override  # noqa: PLW0603 (one process-wide default, like the cache it resets)
    _override = path
    _default.cache_clear()


@cache
def _default() -> ValidationFile:
    if _override is not None:
        return _read(_override)
    if not VALIDATION_PATH.exists():
        log.warning(
            "%s is missing: every asserted claim reads `unchecked`, so freshness never "
            "degrades a claim. Reinstall the package.",
            VALIDATION_PATH,
        )
    return _read(VALIDATION_PATH)


def _read(path: Path) -> ValidationFile:
    try:
        text = path.read_text()
    except FileNotFoundError:
        return ValidationFile()
    try:
        data = json.loads(text)
    except json.JSONDecodeError as e:
        raise PackError(f"{path}: <json>: {e}") from e
    return validate_file(ValidationFile, data, path)


def write_validation(file: ValidationFile, path: Path) -> None:
    """Write `file` deterministically: sorted keys, `indent=1`, a trailing newline.

    The write is atomic: a sibling temp file is replaced over `path`, so a crash never leaves a
    truncated file.
    """
    body = json.dumps(file.model_dump(mode="json"), sort_keys=True, indent=1)
    temp = path.with_name(f".{path.name}.tmp")
    try:
        temp.write_text(body + "\n")
        temp.replace(path)
    except BaseException:
        temp.unlink(missing_ok=True)
        raise


def assertion_digest(claim: Claim) -> str:
    """12 hex digits of sha256 over what the drift run checks for `claim`.

    That is the claim's scope (which dataset or layer is probed) and, per assertion, its
    checker, params and the request its probe sends. A probe's recorded observation and date
    are prose, and do not count.
    """
    probes = claim.probes
    checked = [
        {
            "checker": a.checker,
            "params": a.model_dump(mode="json")["params"],
            "request": probe.query if isinstance(probe, SoqlProbe) else probe.path,
        }
        for a in claim.assertion
        for probe in [probes[a.probe]]
    ]
    scope = claim.scope.model_dump(mode="json", exclude_none=True)
    body = json.dumps({"scope": scope, "assertions": checked}, sort_keys=True)
    return hashlib.sha256(body.encode()).hexdigest()[:12]


def gate_failures(file: ValidationFile, asserted: Mapping[str, Mapping[str, str]]) -> list[str]:
    """One line per claim that blocks a release.

    `asserted` maps a portal id to its claims that have an assertion, each claim id to its
    current `assertion_digest`. A claim fails when it has no entry, when its entry was checked
    against a different assertion (or records no digest), when its outcome is `contradicted`, or
    when it is `inconclusive` for the second run running. An entry for a claim no longer asserted
    is not a failure: the next drift run prunes it.
    """
    failures: list[str] = []
    for portal_id in sorted(asserted):
        checks = file.portals.get(portal_id, {})
        for claim_id in sorted(asserted[portal_id]):
            check = checks.get(claim_id)
            if check is None:
                failures.append(f"{portal_id}: {claim_id}: no entry in validation.json")
            elif check.assertion_digest != asserted[portal_id][claim_id]:
                failures.append(f"{portal_id}: {claim_id}: assertion changed since its last check")
            elif check.outcome == "contradicted":
                failures.append(f"{portal_id}: {claim_id}: contradicted")
            elif check.outcome == "inconclusive" and check.previous_outcome == "inconclusive":
                failures.append(f"{portal_id}: {claim_id}: inconclusive twice running")
    return failures
